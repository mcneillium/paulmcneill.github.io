#!/usr/bin/env node
// Build assets/js/voice-engine.js: the Voice app's own word-prediction engine
// and core board, bundled for the browser playground on the AAC case study.
//
// Nothing here is reimplemented. The prediction code, base model, reranker
// weights, board pages and picture map are read straight from the app
// repository, so the playground behaves exactly like the app's predictor.
//
//   node scripts/build-voice-engine.mjs [path-to-ai-powered-aac-app]
//
// Default app path: ../ai-powered-aac-app (a sibling checkout). Re-run after
// the app's prediction code or vocabulary changes, then commit the output.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
const site = path.resolve(here, '..');
const app = path.resolve(process.argv[2] || path.join(site, '..', 'ai-powered-aac-app'));
const pred = path.join(app, 'src/services/prediction');
const out = path.join(site, 'assets/js/voice-engine.js');

for (const f of ['predictor.js', 'baseModel.json', 'rankerWeights.json']) {
  if (!fs.existsSync(path.join(pred, f))) {
    console.error(`Missing ${f} in ${pred}. Pass the app checkout path as the first argument.`);
    process.exit(1);
  }
}

const git = (...args) => execFileSync('git', ['-C', app, ...args], { encoding: 'utf8' }).trim();
const commit = git('log', '-1', '--format=%h', '--', 'src/services/prediction', 'src/data');
const branch = git('rev-parse', '--abbrev-ref', 'HEAD');

// Board pages and pictures, flattened to plain data. coreVocabulary.js is
// evaluated in Node rather than bundled, because getPage() lazily requires the
// app's custom-word store, which the browser has no use for.
const { corePages } = await import(pathToFileURL(path.join(app, 'src/data/coreVocabulary.js')).href);
const { symbolFor } = await import(pathToFileURL(path.join(app, 'src/data/symbols.js')).href);
const pages = {};
for (const [id, page] of Object.entries(corePages)) {
  pages[id] = {
    id,
    label: page.label,
    buttons: page.buttons.map((b) => ({
      id: b.id,
      label: b.label,
      color: b.color,
      textColor: b.textColor,
      pic: symbolFor(b) || '',
      ...(b.navigateTo ? { nav: b.navigateTo } : {}),
    })),
  };
}

const entry = `
import { createPredictor } from ${JSON.stringify(path.join(pred, 'predictor.js'))};
import base from ${JSON.stringify(path.join(pred, 'baseModel.json'))};
import ranker from ${JSON.stringify(path.join(pred, 'rankerWeights.json'))};
window.VoiceEngine = {
  source: ${JSON.stringify({ repo: 'mcneillium/ai-powered-aac-app', branch, commit })},
  pages: ${JSON.stringify(pages)},
  create: (opts) => createPredictor({ base, ranker, ...(opts || {}) }),
};
`;

const result = await build({
  stdin: { contents: entry, resolveDir: pred, loader: 'js' },
  bundle: true,
  format: 'iife',
  target: 'es2017',
  minify: true,
  legalComments: 'none',
  write: false,
  tsconfigRaw: '{}',
});

const header = `/* Generated by scripts/build-voice-engine.mjs from ${'mcneillium/ai-powered-aac-app'} `
  + `(${branch}, ${commit}). Do not edit by hand. Base model: authored synthetic sentences, 0BSD. */\n`;
const body = result.outputFiles[0].text;
// jekyll-mentions rewrites @tokens in served files; keep the bundle free of them.
if (/(^|[^\w.])@[a-z]/i.test(body)) console.warn('Warning: bundle contains an @token; check jekyll-mentions does not touch it.');
fs.writeFileSync(out, header + body);
console.log(`Wrote ${path.relative(site, out)} (${(Buffer.byteLength(header + body) / 1024).toFixed(1)} KB) from ${branch} ${commit}`);
